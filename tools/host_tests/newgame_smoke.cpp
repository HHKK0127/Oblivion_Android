// newgame_smoke.cpp - deterministic host smoke for the chargen path.
//
// Replays "open the RaceSexMenu -> Randomize -> pick the first playable race ->
// name -> Done -> Yes" without an emulator: load a fixed fixture ESM, run the
// real RaceSexPanel Random body, then drive the SAME commit the renderer uses
// (game/chargen_commit.h) and print the resulting state as JSON on stdout.
//
// Sharing chargen::commit() is deliberate: a smoke that re-implemented the
// commit could stay green while Renderer::setChargenUi's onCommit regressed.
//
// Design rules (docs/evidence/golden/README.md):
//   * deterministic: fixed RNG seed, no clock, relative paths only, fixed key
//     order and %.6f floats. Two runs against the same fixture must print
//     byte-identical JSON.
//   * fixture: docs/evidence/fixtures/minimal.esm, regenerated by
//     tools/host_tests/make_fixture_esm.py.
//
// Exit codes: 0 ok, 2 fixture unreadable, 3 fixture did not load,
//             4 the selected race was not found in the fixture.

#include <algorithm>
#include <cstdio>
#include <cstdint>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

#include "assets/esm_reader.h"
#include "game/chargen_commit.h"
#include "game/npc_manager.h"
#include "game/player.h"
#include "ui/race_sex_panel.h"

namespace {

// Fixed RNG seed for the Random body, so the golden pins the exact 90 slider
// values (RaceSexPanel::setSeed is the test seam; init() would seed from the
// clock).
constexpr uint32_t kRandomSeed = 12345;

std::string readFile(const std::string& path, bool& ok) {
    std::ifstream in(path, std::ios::binary);
    if (!in) {
        ok = false;
        return {};
    }
    std::ostringstream ss;
    ss << in.rdbuf();
    ok = true;
    return ss.str();
}

std::string jsonString(const std::string& s) {
    std::string out = "\"";
    for (char c : s) {
        switch (c) {
            case '"': out += "\\\""; break;
            case '\\': out += "\\\\"; break;
            case '\n': out += "\\n"; break;
            case '\r': out += "\\r"; break;
            case '\t': out += "\\t"; break;
            default: out += c; break;
        }
    }
    out += "\"";
    return out;
}

std::string hex8(uint32_t v) {
    char buf[16];
    std::snprintf(buf, sizeof(buf), "0x%08X", v);
    return buf;
}

std::string f6(float v) {
    char buf[32];
    std::snprintf(buf, sizeof(buf), "%.6f", v);
    return buf;
}

}  // namespace

int main(int argc, char** argv) {
    const std::string fixture =
        argc > 1 ? argv[1] : "docs/evidence/fixtures/minimal.esm";

    bool ok = false;
    const std::string bytes = readFile(fixture, ok);
    if (!ok || bytes.empty()) {
        std::fprintf(stderr, "newgame_smoke: cannot read fixture '%s'\n",
                     fixture.c_str());
        return 2;
    }

    oblivion::ESMManager esm;
    if (!esm.loadPluginFromMemory("minimal.esm",
                                  reinterpret_cast<const uint8_t*>(bytes.data()),
                                  bytes.size())) {
        std::fprintf(stderr, "newgame_smoke: fixture '%s' failed to load\n",
                     fixture.c_str());
        return 3;
    }

    // Seed the panel's race list exactly as Renderer::setChargenUi() does: the
    // playable races (DATA byte32 bit0), in record order.
    std::vector<RaceSexPanel::RaceEntry> playable;
    for (const auto& race : esm.getAllRaces()) {
        if ((race.flags & 1u) == 0) continue;
        if (race.fullName.empty() && race.editorID.empty()) continue;
        playable.push_back({race.formID,
                            race.fullName.empty() ? race.editorID : race.fullName,
                            race.description});
    }
    if (playable.empty()) {
        std::fprintf(stderr, "newgame_smoke: no playable race in fixture\n");
        return 4;
    }

    // --- Chargen session (mirrors the renderer's panel setup) ----------------
    RaceSexPanel panel;
    panel.init();
    panel.setSeed(kRandomSeed);          // deterministic Random
    panel.setAvailableRaces(playable);   // selection index 0 = first playable
    panel.setCurrentRaceFormID(0);       // new game: no current race
    panel.setCurrentName("");
    panel.setPlayerName("SmokeHero");
    panel.doRandom();                    // the Random button's "Yes" body

    // --- Commit (the SAME function the renderer's onCommit calls) -----------
    NpcManager npcMgr;
    npcMgr.setESMManager(&esm);

    Player player;  // default ctor = chargen base (player.h)
    chargen::CommitInput in;
    in.raceChanged = panel.raceChanged();
    in.raceFormID = panel.selectedRaceFormID();
    in.name = panel.playerName();
    const chargen::CommitResult res = chargen::commit(&npcMgr, player, in);

    const oblivion::RaceData* chosen = esm.findRace(player.raceFormID);

    // --- Page / item totals (the panel is the source of truth) --------------
    int itemTotal = 0;
    for (int slot = 0; slot < RaceSexPanel::PAGE_COUNT; ++slot) {
        itemTotal += panel.itemCount(slot);
    }

    // --- The 90 slider values, in builder order (the Random result) ---------
    std::vector<float> sliders;
    for (const auto& e : panel.elements()) {
        if (e.type == RaceSexPanel::ElemType::Slider) sliders.push_back(e.value);
    }

    // Spells sorted: the fixture's SPLO order is stable, but sorting makes the
    // golden independent of record order.
    std::vector<uint32_t> spells = player.knownSpells;
    std::sort(spells.begin(), spells.end());

    // --- Emit JSON (fixed key order, %.6f floats) ---------------------------
    std::ostringstream o;
    o << "{\n";
    o << "  \"name\": " << jsonString(player.name) << ",\n";
    o << "  \"raceFormID\": " << jsonString(hex8(player.raceFormID)) << ",\n";
    o << "  \"raceName\": "
      << jsonString(chosen ? (chosen->fullName.empty() ? chosen->editorID
                                                       : chosen->fullName)
                           : std::string())
      << ",\n";
    o << "  \"raceChanged\": " << (in.raceChanged ? "true" : "false") << ",\n";
    o << "  \"raceApplied\": " << (res.raceApplied ? "true" : "false") << ",\n";
    o << "  \"pageCount\": " << RaceSexPanel::PAGE_COUNT << ",\n";
    o << "  \"itemCount\": " << itemTotal << ",\n";

    const auto& a = player.attributes;
    o << "  \"attributes\": {\n";
    o << "    \"Strength\": " << a.Strength << ",\n";
    o << "    \"Intelligence\": " << a.Intelligence << ",\n";
    o << "    \"Willpower\": " << a.Willpower << ",\n";
    o << "    \"Agility\": " << a.Agility << ",\n";
    o << "    \"Speed\": " << a.Speed << ",\n";
    o << "    \"Endurance\": " << a.Endurance << ",\n";
    o << "    \"Personality\": " << a.Personality << ",\n";
    o << "    \"Luck\": " << a.Luck << "\n";
    o << "  },\n";

    const auto& s = player.skills;
    o << "  \"skills\": {\n";
    o << "    \"Armorer\": " << s.Armorer << ",\n";
    o << "    \"Athletics\": " << s.Athletics << ",\n";
    o << "    \"Blade\": " << s.Blade << ",\n";
    o << "    \"Block\": " << s.Block << ",\n";
    o << "    \"Blunt\": " << s.Blunt << ",\n";
    o << "    \"HandToHand\": " << s.HandToHand << ",\n";
    o << "    \"HeavyArmor\": " << s.HeavyArmor << ",\n";
    o << "    \"Alchemy\": " << s.Alchemy << ",\n";
    o << "    \"Alteration\": " << s.Alteration << ",\n";
    o << "    \"Conjuration\": " << s.Conjuration << ",\n";
    o << "    \"Destruction\": " << s.Destruction << ",\n";
    o << "    \"Illusion\": " << s.Illusion << ",\n";
    o << "    \"Mysticism\": " << s.Mysticism << ",\n";
    o << "    \"Restoration\": " << s.Restoration << ",\n";
    o << "    \"Acrobatics\": " << s.Acrobatics << ",\n";
    o << "    \"LightArmor\": " << s.LightArmor << ",\n";
    o << "    \"Marksman\": " << s.Marksman << ",\n";
    o << "    \"Mercantile\": " << s.Mercantile << ",\n";
    o << "    \"Security\": " << s.Security << ",\n";
    o << "    \"Sneak\": " << s.Sneak << ",\n";
    o << "    \"Speechcraft\": " << s.Speechcraft << "\n";
    o << "  },\n";

    o << "  \"spells\": [";
    for (size_t i = 0; i < spells.size(); ++i) {
        if (i) o << ", ";
        o << jsonString(hex8(spells[i]));
    }
    o << "],\n";

    o << "  \"sliders\": [";
    for (size_t i = 0; i < sliders.size(); ++i) {
        if (i) o << ", ";
        o << f6(sliders[i]);
    }
    o << "]\n";
    o << "}\n";

    std::fputs(o.str().c_str(), stdout);
    return 0;
}
